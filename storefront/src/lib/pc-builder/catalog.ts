/**
 * Filter items by category
 */
export function getCatalogItemsByCategory(category: ComponentCategory): PCComponentItem[] {
  return PC_BUILDER_CATALOG.filter((item) => item.category === category)
}

/**
 * Find component by ID
 */
export function findComponentById(id?: string | null): PCComponentItem | undefined {
  if (!id) return undefined
  return PC_BUILDER_CATALOG.find((item) => item.id === id)
}
